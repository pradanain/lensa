import {test,expect,type Page} from '@playwright/test'
const password='Synthetic-only-password-2026!'
async function login(page:Page,username='admin'){
  await page.goto('/dashboard')
  await page.getByLabel('Nama pengguna',{exact:true}).fill(username)
  await page.getByLabel('Kata sandi',{exact:true}).fill(password)
  await page.getByRole('button',{name:'Masuk ke portal'}).click()
  await page.getByRole('button',{name:'Saya memahami dan berkomitmen',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Ringkasan Data SE2026'})).toBeVisible()
}
test('admin monitors server evidence and browser navigation on desktop and mobile',async({page})=>{
  await login(page)
  await page.getByRole('navigation',{name:'Menu utama'}).getByRole('link',{name:'Keluarga',exact:true}).click()
  await page.getByRole('link',{name:'Monitoring aktivitas',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Monitoring aktivitas',exact:true})).toBeVisible()
  await page.screenshot({path:'../../docs/reports/app/screenshots/compact-monitoring-desktop-synthetic.png',fullPage:true})
  await page.getByRole('combobox',{name:'Filter aktivitas',exact:true}).click()
  await page.getByRole('option',{name:'Buka halaman / bagian',exact:true}).click()
  await expect(page.locator('.activity-table tbody')).toContainText('Dilaporkan browser')
  await expect(page.locator('.activity-table tbody')).toContainText('keluarga')
  await page.getByRole('button',{name:'Periksa integritas',exact:true}).click()
  await expect(page.getByText('Rantai catatan sesuai',{exact:false})).toBeVisible()
  await page.getByRole('button',{name:'Reset filter',exact:true}).click()
  const download=page.waitForEvent('download')
  await page.getByRole('button',{name:'Unduh Excel',exact:true}).click()
  expect((await download).suggestedFilename()).toBe('lensa-aktivitas-utc.xlsx')
  await page.getByRole('tab',{name:'Sesi terbaru',exact:true}).click()
  await expect(page.locator('.activity-sessions')).toContainText('Sesi masih berlaku')
  await page.locator('.activity-sessions').getByRole('button',{name:'Telusuri sesi'}).first().click()
  await expect(page.getByText('Sedang menelusuri sesi',{exact:false})).toBeVisible()
  for(const width of [390,320]){
    await page.setViewportSize({width,height:844})
    await expect(page.locator('.activity-table thead')).toBeHidden()
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  }
  await page.evaluate(()=>{(document.activeElement as HTMLElement)?.blur();window.scrollTo(0,0)})
  await page.screenshot({path:'../../docs/reports/app/screenshots/activity-mobile-synthetic.png',fullPage:false})
})
test('analyst cannot open monitoring or download evidence',async({page})=>{
  await login(page,'analyst')
  await expect(page.getByRole('link',{name:'Monitoring aktivitas',exact:true})).toHaveCount(0)
  await page.goto('/monitoring')
  await expect(page.getByText('Monitoring aktivitas hanya tersedia untuk administrator.',{exact:true})).toBeVisible()
  expect((await page.request.get('/api/v1/activity')).status()).toBe(403)
  expect((await page.request.get('/api/v1/activity/integrity')).status()).toBe(403)
})


test('compact commitment aligns icon and title and emphasizes personal responsibility',async({page})=>{
  await page.goto('/usaha')
  await page.getByLabel('Nama pengguna',{exact:true}).fill('admin')
  await page.getByLabel('Kata sandi',{exact:true}).fill(password)
  await page.getByRole('button',{name:'Masuk ke portal'}).click()
  const dialog=page.getByRole('dialog',{name:'Pakta integritas',exact:true})
  await expect(dialog.locator('.commitment-points li')).toHaveCount(3)
  await expect(dialog.locator('strong').last()).toContainText('bertanggung jawab penuh')
  for(const width of [1280,390,320]){
    await page.setViewportSize({width,height:844})
    const icon=await dialog.locator('.commitment-emblem').boundingBox()
    const title=await dialog.getByRole('heading',{name:'Pakta integritas'}).boundingBox()
    expect(Math.abs(icon!.y+icon!.height/2-title!.y-title!.height/2)).toBeLessThan(3)
    expect((await dialog.boundingBox())!.width).toBeLessThanOrEqual(560)
    expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
    await page.screenshot({path:'../../docs/reports/app/screenshots/compact-commitment-'+width+'-synthetic.png'})
  }
  await dialog.getByRole('button',{name:'Saya memahami dan berkomitmen',exact:true}).click()
  await expect(dialog).toHaveCount(0)
})

test('compact account management supports search password visibility and account actions',async({page})=>{
  await login(page)
  await page.getByRole('link',{name:'Kelola pengguna',exact:true}).click()
  await page.getByLabel('Nama pengguna',{exact:true}).fill('layout.user')
  const temporary=page.getByLabel('Kata sandi sementara',{exact:true})
  await temporary.fill('a')
  await page.getByRole('button',{name:'Tampilkan kata sandi',exact:true}).click()
  await expect(temporary).toHaveAttribute('type','text')
  await page.getByRole('button',{name:'Sembunyikan kata sandi',exact:true}).click()
  await expect(temporary).toHaveAttribute('type','password')
  await page.getByRole('button',{name:'Tambah pengguna',exact:true}).click()
  await expect(page.getByRole('status')).toContainText('Pengguna dibuat.')
  await page.getByLabel('Cari pengguna',{exact:true}).fill('layout.user')
  await expect(page.locator('.account-row')).toHaveCount(1)
  const account=page.locator('.account-row').filter({hasText:'layout.user'})
  await account.getByRole('combobox').click()
  await page.getByRole('option',{name:'Administrator',exact:true}).click()
  await expect(account.getByRole('combobox')).toHaveAttribute('data-value','admin')
  await expect(account.getByRole('button',{name:'Nonaktifkan layout.user',exact:true})).toBeEnabled()
  await account.getByRole('button',{name:'Nonaktifkan layout.user',exact:true}).click()
  await expect(account.getByRole('button',{name:'Aktifkan layout.user',exact:true})).toBeEnabled()
  await account.getByRole('button',{name:'Aktifkan layout.user',exact:true}).click()
  await expect(account.getByRole('button',{name:'Nonaktifkan layout.user',exact:true})).toBeEnabled()
  await page.getByLabel('Cari pengguna',{exact:true}).fill('absent.synthetic')
  await expect(page.getByText('Tidak ada pengguna yang sesuai.',{exact:true})).toBeVisible()
  await page.getByLabel('Cari pengguna',{exact:true}).fill('')
  await expect(page.locator('.account-row')).not.toHaveCount(0)
  await page.getByRole('heading',{name:'Kelola pengguna',exact:true}).click()
  for(const width of [1280,390,320]){
    await page.setViewportSize({width,height:844})
    expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
    await page.screenshot({path:'../../docs/reports/app/screenshots/compact-accounts-'+width+'-synthetic.png',fullPage:true})
  }
})
