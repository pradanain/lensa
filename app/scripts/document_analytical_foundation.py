def read(path):
    return json.loads((ROOT / path).read_text(encoding='utf-8'))


def write(path, text):
    target = ROOT / path
    target.parent.mkdir(parents=True, exist_ok=True)
    if target.suffix == '.md':
        text=rebase_markdown(text,original_document(path),path)
    target.write_text(text.rstrip() + '\n', encoding='utf-8')


def cell(value):
    if isinstance(value, (list, dict)):
        value = json.dumps(value, ensure_ascii=False)
    return str(value).replace('|', '\\|').replace('\n', ' ')


def table(headers, rows):
    return '\n'.join(['| ' + ' | '.join(headers) + ' |',
                      '| ' + ' | '.join('---' for _ in headers) + ' |'] +
                     ['| ' + ' | '.join(cell(v) for v in row) + ' |' for row in rows])


def test_result(name):
    result = ET.parse(ROOT / 'docs/reports/analytics' / name).getroot().find('testsuite').attrib
    return {k: result[k] for k in ('tests', 'failures', 'errors', 'skipped', 'time', 'timestamp')}


